/* ===== スキル・魔法ごとの効果プログラム =====
   名前・MP・待機ターン・説明・必要条件は data/equipment.xlsx で編集する。ここには「使ったとき何が起きるか」だけを書く。
   キーは data/equipment.xlsx の「スキル」シートの ID と対応している。
   calc(P) は {ok:使えるか, dmg, heal, shield, barrier, poison, burn, bleed, stun, freeze, weaken, vulnerable, drain, gold, hpCost, dbl} などを返す。 */
const SKILL_FX={
 smash:P=>({ok:P.high>0,dmg:dmgOf(P.sumHigh*P.mult*1.5)}),
 count:P=>({ok:(P.cnt[1]||0)>0,dmg:dmgOf((P.cnt[1]||0)*P.S)}),
 pair:P=>({ok:P.pairs>0,dmg:dmgOf(P.S*P.pairs*1.5)}),
 straight:P=>({ok:P.run>=3,dmg:dmgOf(P.S*P.run*1.5)}),
 venom:P=>({ok:P.odd>0,dmg:dmgOf(P.sumOdd),poison:Math.max(1,R(P.sumOdd*.4))}),
 double:P=>{const c=Math.max(1,R(p.maxHp*.1));return {ok:!p.dbl&&p.hp>c,hpCost:c,dbl:true}},
 fire:P=>({ok:true,dmg:dmgOf(P.S*P.mult*1.5)}),
 thunder:P=>({ok:true,dmg:dmgOf(P.S*P.mult*2.5)}),
 ice:P=>({ok:true,dmg:dmgOf(P.S*P.mult*.8),freeze:true}),
 drain:P=>({ok:true,dmg:dmgOf(P.S*P.mult*.8),drain:true}),
 heal:P=>({ok:p.hp<p.maxHp,heal:Math.max(1,R(P.S*P.mult*.8))}),
 barrier:P=>({ok:true,barrier:Math.max(1,R(P.S*P.mult*1.5))}),
 quake:P=>({ok:true,dmg:dmgOf(P.S*P.mult*1.8)}),
 starfall:P=>({ok:true,dmg:dmgOf(P.S*P.mult*3)}),
 mend:P=>({ok:p.hp<p.maxHp,heal:Math.max(1,R(P.S*P.mult*1.5))}),
 weakness:P=>({ok:true,dmg:dmgOf(P.S*P.mult),weaken:true}),
 venomburst:P=>({ok:true,dmg:dmgOf(P.S*P.mult),poison:Math.max(1,R(P.S*P.mult*.5))}),
 seven:P=>({ok:P.S%7===0,dmg:dmgOf(P.S*7)}),
 oneslash:P=>({ok:(P.cnt[1]||0)===1,dmg:dmgOf(P.S*10)}),
 royal:P=>({ok:[1,2,3,4,5,6].every(v=>(P.cnt[v]||0)>0),dmg:dmgOf(P.S*12)}),
 evensmash:P=>({ok:P.N>0&&P.even===P.N,dmg:dmgOf(P.S*5)}),
 oddrush:P=>({ok:P.odd>0,dmg:dmgOf(P.odd*P.sumOdd)}),
 sixgod:P=>({ok:(P.cnt[6]||0)>0,dmg:dmgOf(P.S*Math.pow(P.cnt[6]||0,2))}),
 triangle:P=>({ok:(P.cnt[3]||0)>=3,dmg:dmgOf(P.S*6)}),
 quad:P=>({ok:(P.cnt[4]||0)>=4,dmg:dmgOf(P.S*8)}),
 pentagram:P=>({ok:(P.cnt[5]||0)>=5,dmg:dmgOf(P.S*12)}),
 jackpot:P=>({ok:P.jack,dmg:dmgOf(P.S*20)}),
 meteor:P=>({ok:true,dmg:dmgOf(P.S*5)}),
 nova:P=>({ok:true,dmg:dmgOf(P.S*8)}),
 superheal:P=>({ok:p.hp<p.maxHp,heal:Math.max(1,R(P.S*P.mult*2))}),
 lifeburst:P=>({ok:true,dmg:dmgOf(P.S*3)}),
 goldrain:P=>({ok:true,gold:Math.max(1,R(P.S))}),
 sacrifice:P=>{const c=Math.max(1,R(p.maxHp*.2));return {ok:p.hp>c,hpCost:c,dmg:dmgOf(P.S*8)}},
 timebreak:P=>({ok:true,freeze:true}),
 blooddrain:P=>({ok:true,dmg:dmgOf(P.S*P.mult*2),drain:true}),
 flare:P=>({ok:true,dmg:dmgOf(P.S*P.mult),burn:Math.max(1,R(P.S*.5))}),
 rupture:P=>({ok:true,dmg:dmgOf(P.S*P.mult),bleed:Math.max(1,R(P.S*.35))}),
 stunstrike:P=>({ok:true,dmg:dmgOf(P.S*P.mult*1.2),stun:true}),
 expose:P=>({ok:true,vulnerable:true}),
};
